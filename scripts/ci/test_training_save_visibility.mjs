import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
const read=path=>readFileSync(new URL("../../"+path,import.meta.url),"utf8");
const html=read("rust/volley-app/static/studio.html");
const js=read("rust/volley-app/static/studio.js");
const css=read("rust/volley-app/static/studio.css");
const rust=read("rust/volley-app/src/touch_annotation.rs");
const panel=html.slice(html.indexOf('<section id="studio-training-panel"'),html.indexOf('id="studio-training-list"'));
assert.equal((panel.match(/id="studio-annotation-review"/g)||[]).length,1);
assert.ok(panel.indexOf('id="studio-annotation-review"')>0);
assert.ok(panel.indexOf('id="studio-annotation-review"')<panel.indexOf('id="studio-training-save"'),
  "Save annotated video must be visible before pose-example editor");
assert.ok(panel.indexOf('id="studio-annotation-save-state"')<panel.indexOf('id="studio-training-save"'));
assert.ok(panel.includes('id="studio-annotation-save"'),"Manual corrections need an explicit persistence action");
assert.ok(panel.includes("Завершить проверку видео"),"Final review must be separate from saving draft edits");
assert.ok(panel.indexOf('id="studio-annotation-save"')<panel.indexOf('id="studio-annotation-review"'));
assert.ok(css.includes(".studio-annotation-save-bar"));
assert.ok(js.includes('annotation.review.addEventListener("click",()=>editAnnotation("review"))'));
assert.ok(js.includes('action:"save"'),"Trajectory and manual labels must be saved explicitly");
assert.ok(js.includes('annotation.save.addEventListener("click"'));
assert.ok(rust.includes('"review" => {')&&rust.includes('v.reviewed = true')&&rust.includes('save(&state, &lib)?'));
const start=js.indexOf("  const annotationSavePresentation=");
const end=js.indexOf("  const annotationSorted=",start);
assert.ok(start>0&&end>start);
const {annotationSavePresentation}=runInNewContext(js.slice(start,end)+
 "\n({annotationSavePresentation})",{annotation:{dirty:false},annotationSourceValid:()=>true});
const fresh={touches:[],rallies:[],reviewed:false};
const saved={touches:[{id:"a"}],rallies:[{id:"r"}],reviewed:false};
const reviewed={...saved,reviewed:true};
let state=annotationSavePresentation(null,false,false);
assert.equal(state.disabled,true);assert.match(state.text,/CPU/);
state=annotationSavePresentation(null,true,false);
assert.equal(state.disabled,true);assert.match(state.text,/Рассчитать касания|расчёт/);
state=annotationSavePresentation(fresh,true,false);
assert.equal(state.disabled,true);assert.match(state.text,/розыгрыш/);
state=annotationSavePresentation(saved,true,false);
assert.equal(state.disabled,false);assert.match(state.text,/Разметка сохранена/);
state=annotationSavePresentation(reviewed,true,false);
assert.equal(state.disabled,true);assert.match(state.text,/проверена/);
state=annotationSavePresentation(saved,true,true);
assert.equal(state.disabled,true);assert.match(state.text,/Сохранение/);
console.log("Training annotation save: visible above example editor, live status, persisted reviewed action: OK");
