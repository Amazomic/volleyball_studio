import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";

const script=readFileSync(new URL("../../rust/volley-app/static/studio_tabs.js",import.meta.url),"utf8");
const css=readFileSync(new URL("../../rust/volley-app/static/studio.css",import.meta.url),"utf8");
const start=script.indexOf("  const playerTrackingSummary=(run,id)=>{");
const end=script.indexOf("  const stageResultText=",start);
assert.ok(start>=0&&end>start,"Phase-specific summaries must be defined on analysis screen");
const context={};
runInNewContext(script.slice(start,end)+"\nthis.summary=playerTrackingSummary;",context);
const stats={raw_detections:2546,total_track_ids:301,short_track_ids:21,track_ids:280};
const run={player_tracking_stats:stats};
const players=context.summary(run,"players");
const tracking=context.summary(run,"tracking");
assert.match(players.text,/2[\s\u00a0\u202f]*546 обнаружений/);
assert.doesNotMatch(players.text+players.title,/ByteTrack|Track ID/);
assert.match(tracking.text,/280 ID после ByteTrack/);
assert.match(tracking.title,/301 Track ID/);
assert.match(tracking.title,/21 коротких ID/);
assert.match(tracking.title,/не подтверждённые личности/);
assert.doesNotMatch(tracking.text+tracking.title,/RF-DETR|обнаружений/);
assert.equal(context.summary(run,"pose"),null);
assert.equal(context.summary({player_tracking_stats:{raw_detections:0}},"players").text,"0 обнаружений");
assert.equal(context.summary({player_tracking_stats:{total_track_ids:0,short_track_ids:0,track_ids:0}},"tracking").text,"0 ID после ByteTrack");
assert.equal(context.summary({player_tracking_stats:{raw_detections:5}},"tracking"),null);
assert.equal(context.summary({player_tracking_stats:{total_track_ids:2,short_track_ids:0,track_ids:2}},"players"),null);
assert.equal(context.summary({},"players"),null);
assert.equal(context.summary(null,"tracking"),null);
assert.equal(context.summary({player_tracking_stats:{total_track_ids:1,short_track_ids:0,track_ids:2}},"tracking"),null);
assert.equal(context.summary({player_tracking_stats:{raw_detections:-1}},"players"),null);
assert.match(script,/if\(id==="players"\|\|id==="tracking"\)cell\.append\(make\("small","analysis-flow-node-stage-metrics hidden"\)\)/);
assert.match(script,/if\(id==="players"\|\|id==="tracking"\)\{\s*const metrics=playerTrackingSummary\(run,id\)/);
assert.match(script,/node\.parentElement\.querySelector\("\.analysis-flow-node-stage-metrics"\)/);
assert.match(css,/\.analysis-flow-node-stage-metrics\{/);
assert.doesNotMatch(script,/analysis-flow-node-player-ids/);
console.log("Phase-owned RF-DETR / ByteTrack counters: OK");
